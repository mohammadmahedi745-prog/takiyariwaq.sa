-- Supabase secure admin and ordering schema for TAKIYA RIWAQ
-- 1) Create a Supabase project and enable Email/Password Authentication.
-- 2) Run this SQL in Supabase SQL Editor.
-- 3) Create your owner account in Authentication > Users.
-- 4) Add that account's auth.users UUID to admin_users using the SQL editor.
-- Never expose the service_role key in frontend code.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admin_users enable row level security;
create policy "admins can read own admin record" on public.admin_users
for select to authenticated using (user_id = auth.uid());

create table if not exists public.products (
  id text primary key,
  name_en text not null,
  name_ar text not null,
  category text not null,
  price numeric(10,2) not null check (price >= 0),
  original_price numeric(10,2),
  image_url text,
  available boolean not null default true,
  visible boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.products enable row level security;
create policy "public can view visible products" on public.products
for select to anon, authenticated using (visible = true);
create policy "admins manage products" on public.products
for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text,
  customer_phone text,
  items jsonb not null,
  total numeric(10,2) not null check (total >= 0),
  language text not null default 'en',
  status text not null default 'new',
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
create policy "customers can create orders" on public.orders
for insert to anon, authenticated with check (true);
create policy "admins can view and update orders" on public.orders
for all to authenticated
using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

